#!/usr/bin/env bash
# Writes ios/Flutter/LazerAudio.xcconfig so the Runner target links the iOS
# engine archives produced by ci/build-ios-audio.sh.
#
# The file is git-ignored: it overrides the committed default archive directory
# when CI or a custom build has already prepared its libraries. Without it, the
# Runner build phase builds the native engine into the default per-SDK directory.
#
#   bash ci/ios-audio-xcconfig.sh <dir with the .a archives> [device|simulator]
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
platform="${2:-device}"
case "$platform" in
    device) sdk_name="iphoneos" ;;
    simulator) sdk_name="iphonesimulator" ;;
    *) echo "Platform must be device or simulator." >&2; exit 2 ;;
esac
lib_dir="${1:-$repo/build/ios-audio/$platform/stage/lib}"
if [[ ! -d "$lib_dir" ]]; then
    echo "Missing iOS engine libraries at $lib_dir; run ci/build-ios-audio.sh first." >&2
    exit 2
fi
lib_dir="$(cd "$lib_dir" && pwd)"
for name in liblazer-audio.a liblazer-audio-bridge.a \
    libavformat.a libavcodec.a libavutil.a libswresample.a; do
    if [[ ! -f "$lib_dir/$name" ]]; then
        echo "Missing $name in $lib_dir" >&2
        exit 1
    fi
done

out="$repo/ios/Flutter/LazerAudio.xcconfig"
cat > "$out" <<'EOF'
// Generated by ci/ios-audio-xcconfig.sh. Do not edit; not committed.
// Override only this SDK. Other SDKs retain their default native build directory.
// LazerAudio.defaults.xcconfig owns the static link/export flags.
EOF
printf 'LAZER_AUDIO_LIB_DIR[sdk=%s*] = %s\n' "$sdk_name" "$lib_dir" >> "$out"

printf 'Wrote %s\n' "$out"
cat "$out"
