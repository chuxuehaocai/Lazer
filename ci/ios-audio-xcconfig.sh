#!/usr/bin/env bash
# Writes ios/Flutter/LazerAudio.xcconfig so the Runner target links the iOS
# engine archives produced by ci/build-ios-audio.sh.
#
# The file is git-ignored on purpose: a checkout that has not built the engine
# still builds the app, which then runs on just_audio exactly as before. The
# committed Debug/Release xcconfigs include it with `#include?`, so its absence
# is not an error.
#
#   bash ci/ios-audio-xcconfig.sh <dir with the .a archives>
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
lib_dir="${1:-$repo/build/ios-audio/device/stage/lib}"
if [[ ! -d "$lib_dir" ]]; then
    echo "Missing iOS engine libraries at $lib_dir; run ci/build-ios-audio.sh first." >&2
    exit 2
fi
lib_dir="$(cd "$lib_dir" && pwd)"
for name in liblazer-audio.a liblazer-audio-bridge.a \
    libavformat.a libavcodec.a libavutil.a libswresample.a; do
    if [[ ! -f "$lib_dir/$name" ]]; then
        echo "Missing $name in $lib_dir" >&2
        exit 1
    fi
done

out="$repo/ios/Flutter/LazerAudio.xcconfig"
cat > "$out" <<'EOF'
// Generated by ci/ios-audio-xcconfig.sh. Do not edit; not committed.
// iOS loads no image it was not shipped with, so the engine, its reader bridge
// and FFmpeg are static archives linked into the Runner binary and reached
// through DynamicLibrary.process(). -export_dynamic keeps the ABI symbols in
// the executable's export trie so dlsym(RTLD_DEFAULT) finds them.
LAZER_AUDIO_LIB_DIR = @LIB_DIR@
LIBRARY_SEARCH_PATHS = $(inherited) "$(LAZER_AUDIO_LIB_DIR)"
OTHER_LDFLAGS = $(inherited) -Wl,-force_load,"$(LAZER_AUDIO_LIB_DIR)/liblazer-audio.a" -Wl,-force_load,"$(LAZER_AUDIO_LIB_DIR)/liblazer-audio-bridge.a" -lavformat -lavcodec -lavutil -lswresample -framework AudioToolbox -framework AVFAudio -framework CoreAudio -framework CoreFoundation -lc++ -Wl,-export_dynamic
EOF
# The path has no spaces in practice, but sed with | keeps it safe anyway.
sed -i.bak "s|@LIB_DIR@|$lib_dir|g" "$out"
rm -f "$out.bak"

printf 'Wrote %s\n' "$out"
cat "$out"
