<#
.SYNOPSIS
    Generates the Android release keystore and the GitHub Actions secret bundle.

.DESCRIPTION
    Creates a JKS keystore for signing release APKs, writes the git-ignored
    android/key.properties that app/build.gradle.kts reads, and exports everything
    needed to configure the repository secrets into dist/android-signing/.

    The keystore is the root of trust for every future update of the app: keep
    dist/android-signing/ offline, lose it once and no installed build can ever be
    upgraded in place again.

.EXAMPLE
    ./ci/generate-android-keystore.ps1
    ./ci/generate-android-keystore.ps1 -Alias lazer-release -ValidityDays 10000
    ./ci/generate-android-keystore.ps1 -Force   # replace an existing keystore
#>
[CmdletBinding()]
param(
    [string] $Alias = 'lazer-release',
    [int] $KeySize = 4096,
    [int] $ValidityDays = 10000,
    [string] $DistinguishedName = 'CN=Lazer, OU=Android Release, O=chuxuehaocai, L=Shanghai, ST=Shanghai, C=CN',
    [string] $StorePassword,
    [string] $KeyStorePath,
    [switch] $Force
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# keytool reports progress on both streams; keep them readable in a UTF-8 console.
try { [Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false) } catch { }

$repoRoot = Split-Path -Parent $PSScriptRoot
$appDir = Join-Path $repoRoot 'android/app'
$keyPropertiesPath = Join-Path $repoRoot 'android/key.properties'
$exportDir = Join-Path $repoRoot 'dist/android-signing'
if (-not $KeyStorePath) { $KeyStorePath = Join-Path $appDir 'upload-keystore.jks' }

$keytoolCommand = Get-Command keytool -ErrorAction SilentlyContinue
if (-not $keytoolCommand) {
    throw 'keytool not found. Install a JDK (17+) and put its bin directory on PATH.'
}
$keytoolPath = $keytoolCommand.Source

function Invoke-Keytool {
    <#
        Runs keytool and returns its combined output. keytool writes warnings such
        as the JKS-format notice to stderr, which PowerShell 5.1 turns into a
        terminating NativeCommandError while $ErrorActionPreference is Stop.
    #>
    param([Parameter(Mandatory)][string[]] $Arguments)

    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $output = & $keytoolPath '-J-Dstdout.encoding=UTF-8' '-J-Dstderr.encoding=UTF-8' @Arguments
    } finally {
        $ErrorActionPreference = $previous
    }
    if ($LASTEXITCODE -ne 0) {
        throw "keytool $($Arguments[0]) failed with exit code $LASTEXITCODE`n$($output -join [Environment]::NewLine)"
    }
    return $output
}

if ((Test-Path -LiteralPath $KeyStorePath) -and -not $Force) {
    throw "$KeyStorePath already exists. Re-run with -Force only if you intend to abandon the current release key."
}
if ((Test-Path -LiteralPath $keyPropertiesPath) -and -not $Force) {
    throw "$keyPropertiesPath already exists. Re-run with -Force to replace it."
}

if ($Force) {
    # An old release key can never be thrown away safely, so keep a copy instead.
    $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    foreach ($stale in @($KeyStorePath, $keyPropertiesPath)) {
        if (Test-Path -LiteralPath $stale) {
            Move-Item -LiteralPath $stale -Destination "$stale.bak-$stamp"
            Write-Host "Kept previous $stale as $stale.bak-$stamp"
        }
    }
}

# 32 characters, unambiguous alphabet: survives copy/paste into GitHub, shells and keytool.
if (-not $StorePassword) {
    $alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
    $bytes = New-Object byte[] 32
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    $StorePassword = -join ($bytes | ForEach-Object { $alphabet[$_ % $alphabet.Length] })
}

New-Item -ItemType Directory -Force -Path $appDir, $exportDir | Out-Null

Write-Host "Generating $KeyStorePath"
Invoke-Keytool @(
    '-genkeypair',
    '-keystore', $KeyStorePath,
    '-storetype', 'JKS',
    '-alias', $Alias,
    '-keyalg', 'RSA',
    '-keysize', $KeySize,
    '-sigalg', 'SHA256withRSA',
    '-validity', $ValidityDays,
    '-storepass', $StorePassword,
    '-keypass', $StorePassword,
    '-dname', $DistinguishedName,
    '-noprompt'
) | Out-Host

$keyProperties = @(
    '# Generated by ci/generate-android-keystore.ps1. Never commit this file.',
    "storePassword=$StorePassword",
    "keyPassword=$StorePassword",
    "keyAlias=$Alias",
    'storeFile=upload-keystore.jks'
) -join "`n"
[System.IO.File]::WriteAllText($keyPropertiesPath, $keyProperties + "`n", [System.Text.UTF8Encoding]::new($false))

$exportedKeyStore = Join-Path $exportDir 'upload-keystore.jks'
Copy-Item -LiteralPath $KeyStorePath -Destination $exportedKeyStore -Force
$base64Path = Join-Path $exportDir 'upload-keystore.jks.base64.txt'
[System.IO.File]::WriteAllText(
    $base64Path,
    [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($exportedKeyStore)),
    [System.Text.UTF8Encoding]::new($false)
)

# apksigner prints the SHA-256 digest of the DER certificate, so hash the exported
# certificate instead of parsing human-readable keytool output.
$certificatePath = Join-Path ([System.IO.Path]::GetTempPath()) ("lazer-signing-{0}.cer" -f [guid]::NewGuid())
Invoke-Keytool @(
    '-exportcert',
    '-keystore', $KeyStorePath,
    '-storetype', 'JKS',
    '-alias', $Alias,
    '-storepass', $StorePassword,
    '-file', $certificatePath
) | Out-Null
try {
    $fingerprint = (Get-FileHash -LiteralPath $certificatePath -Algorithm SHA256).Hash.ToLowerInvariant()
} finally {
    Remove-Item -LiteralPath $certificatePath -Force -ErrorAction SilentlyContinue
}

$secrets = @(
    'GitHub repository secrets (Settings -> Secrets and variables -> Actions -> New repository secret)',
    '',
    'ANDROID_KEYSTORE_BASE64   = (paste the whole content of upload-keystore.jks.base64.txt)',
    "ANDROID_KEYSTORE_PASSWORD = $StorePassword",
    "ANDROID_KEY_ALIAS         = $Alias",
    "ANDROID_KEY_PASSWORD      = $StorePassword",
    '',
    "Certificate SHA-256 fingerprint: $fingerprint",
    "Keystore file: $exportedKeyStore",
    "Local key.properties: $keyPropertiesPath",
    '',
    'Keep this directory offline. Without the keystore no future build can upgrade an installed app.',
    'Workflow: .github/workflows/build.yml (android job).'
) -join "`n"
$secretsPath = Join-Path $exportDir 'github-secrets.txt'
[System.IO.File]::WriteAllText($secretsPath, $secrets + "`n", [System.Text.UTF8Encoding]::new($false))

Write-Host ''
Write-Host $secrets
Write-Host ''
Write-Host "Exported to $exportDir"
